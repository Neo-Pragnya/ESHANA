#!/usr/bin/env python3
"""Render planning/backlog.json to planning/TRACKING.md and validate it.

    python3 scripts/tracking_report.py           # rewrite TRACKING.md
    python3 scripts/tracking_report.py --check   # fail if TRACKING.md is stale or the backlog is invalid

Status words are used exactly:
  proposed     designed or listed, nothing built
  implemented  code exists
  verified     a test, gate scenario or measured comparison proves it (evidence required)
  released     published to a registry (evidence required)
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKLOG = ROOT / "planning" / "backlog.json"
REPORT = ROOT / "planning" / "TRACKING.md"
STATUSES = ["proposed", "implemented", "verified", "released"]
TRACKS = ["primary", "secondary"]


def validate(data: dict) -> list[str]:
    errors: list[str] = []
    seen: set[str] = set()
    areas = {a["id"] for a in data["areas"]}
    for t in data["tasks"]:
        tid = t.get("id", "?")
        if tid in seen:
            errors.append(f"duplicate id {tid}")
        seen.add(tid)
        if t.get("area") not in areas:
            errors.append(f"{tid}: unknown area {t.get('area')!r}")
        if t.get("status") not in STATUSES:
            errors.append(f"{tid}: status {t.get('status')!r} is not one of {STATUSES}")
        if t.get("track") not in TRACKS:
            errors.append(f"{tid}: track {t.get('track')!r} is not one of {TRACKS}")
        if t.get("status") in ("verified", "released") and not str(t.get("evidence", "")).strip():
            errors.append(f"{tid}: status {t['status']} needs evidence")
        if not str(t.get("title", "")).strip():
            errors.append(f"{tid}: empty title")
        for ref in t.get("evidence_paths", []):
            if not (ROOT / ref).exists():
                errors.append(f"{tid}: evidence path {ref} does not exist")
        for dep in t.get("depends_on", []):
            if dep not in {x["id"] for x in data["tasks"]}:
                errors.append(f"{tid}: depends_on unknown task {dep}")
    return errors


def render(data: dict) -> str:
    tasks = data["tasks"]
    by_status = Counter(t["status"] for t in tasks)
    out = [
        "# ESHANA tracking",
        "",
        "<!-- Generated by scripts/tracking_report.py from planning/backlog.json. Do not edit by hand. -->",
        "",
        f"**{len(tasks)} tasks.** "
        + " · ".join(f"{s} {by_status.get(s, 0)}" for s in STATUSES),
        "",
        "Status words are exact: *proposed* (nothing built) · *implemented* (code exists) · *verified* (a test, gate scenario or "
        "measurement proves it) · *released* (published). `verified` and `released` need evidence.",
        "",
        "## By area",
        "",
        "| Area | Proposed | Implemented | Verified | Released |",
        "|---|---:|---:|---:|---:|",
    ]
    per_area: dict[str, Counter] = defaultdict(Counter)
    for t in tasks:
        per_area[t["area"]][t["status"]] += 1
    for a in data["areas"]:
        c = per_area[a["id"]]
        out.append(f"| {a['title']} | " + " | ".join(str(c.get(s, 0)) for s in STATUSES) + " |")
    out.append("")
    for a in data["areas"]:
        rows = [t for t in tasks if t["area"] == a["id"]]
        if not rows:
            continue
        out += [f"## {a['title']}", "", a.get("summary", ""), "", "| Id | Task | Track | Status | Evidence / note |", "|---|---|---|---|---|"]
        for t in rows:
            note = (t.get("evidence") or t.get("note") or "").replace("|", "\\|").replace("\n", " ")
            out.append(f"| {t['id']} | {t['title']} | {t['track']} | **{t['status']}** | {note} |")
        out.append("")
    nxt = [t for t in tasks if t["status"] == "proposed" and t["track"] == "primary"]
    out += ["## Next primary tasks (proposed)", ""]
    out += [f"- **{t['id']}** {t['title']}" for t in nxt] or ["- none"]
    out.append("")
    return "\n".join(out)


def main() -> int:
    data = json.loads(BACKLOG.read_text(encoding="utf-8"))
    errors = validate(data)
    if errors:
        print("backlog invalid:\n  " + "\n  ".join(errors), file=sys.stderr)
        return 1
    text = render(data)
    if "--check" in sys.argv:
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != text:
            print("planning/TRACKING.md is stale: run `make tracking`", file=sys.stderr)
            return 1
        print(f"tracking ok: {len(data['tasks'])} tasks")
        return 0
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}: {len(data['tasks'])} tasks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
