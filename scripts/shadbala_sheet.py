#!/usr/bin/env python3
"""Write docs/reference/shadbala-reconciliation.md: ESHANA's ṣaḍbala per graha and per component for the published
reference chart, the printed totals, and the convention behind every component.

    .venv/bin/python scripts/shadbala_sheet.py

The reference printout gives totals only. Per-component deltas need the reference's own component values; until
they are supplied, the sheet records ESHANA's side and names the convention variants that could account for the
total differences. It never adjusts a component to close a total.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "accuracy"))
import lib  # noqa: E402
from eshana import execute  # noqa: E402

OUT = ROOT / "docs" / "reference" / "shadbala-reconciliation.md"
GRAHAS = ["sun", "moon", "mars", "mercury", "jupiter", "venus", "saturn"]
CONVENTIONS = [
    ("Sthāna: uccha", "60 virūpas at exaltation, falling linearly to 0 at debilitation", "same in the common texts"),
    ("Sthāna: saptavargaja", "dignity points in D1, D2, D3, D7, D9, D12, D30 (vedic.bala pack)", "programs differ on the dignity table (adhimitra … adhiśatru) and on D2/D3 schemes"),
    ("Sthāna: ojayugma, kendrādi, drekkāṇa", "BPHS rules as named in the pack", "few variants"),
    ("Dig", "60 at the graha's strongest bhāva cusp, falling linearly to 0 opposite", "cusp from the Ascendant/MC vs from whole-sign houses"),
    ("Kāla: natonnata", "from the Sun's hour angle", "some programs use the time from midnight or noon"),
    ("Kāla: pakṣa", "from the Moon–Sun elongation; the Moon's value doubled", "doubling for the Moon only, or for all benefics"),
    ("Kāla: tribhāga, abda, māsa, vāra, horā", "lords from the weekday of the last Meṣa ingress and the Sun's last sign ingress", "the year and month lords are where programs differ most (ingress vs calendar)"),
    ("Kāla: ayana", "from the declination", "the Sun's ayana bala doubled in some programs"),
    ("Kāla: yuddha", "reported as a condition, not added", "added to the winner and taken from the loser in some programs"),
    ("Ceṣṭā", "eight motion states against the mean daily motion; the Sun takes its ayana bala, the Moon its pakṣa bala", "the cheṣṭā-kendra formula (from the mean longitude and the śīghrocca) is the main alternative and can move a graha by tens of virūpas"),
    ("Naisargika", "fixed values (60, 51.4, 42.9, 34.3, 25.7, 17.1, 8.6)", "same everywhere"),
    ("Dṛk", "(sputa drishti from benefics − from malefics) / 4; the Moon counts by pakṣa", "quarter vs full value; which grahas are benefic (Mercury by association)"),
]


def main() -> None:
    c = lib.load("published.json")["parashara_light_charts"][0]
    req = {"op": "chart", "system": "vedic", "features": ["shadbala"],
           "when": {"date": c["date"], "time": c["time"], "utc_offset_minutes": c["utc_offset_minutes"]},
           "place": {"latitude": c["lat"], "longitude": c["lon"]},
           "config": {"zodiac": "sidereal", "ayanamsha": "lahiri", "node_model": "true"}}
    env = execute(req)
    sb = next(a for a in env["derived_attributes"] if a["id"] == "vedic.shadbala")
    v, printed = sb["value"]["grahas"], c["printed"]["shadbala_virupa"]
    f = lambda x: "—" if x is None else f"{x:.1f}"  # noqa: E731
    lines = ["---", 'title: "Ṣaḍbala reconciliation sheet"',
             'description: "ESHANA\'s ṣaḍbala per graha and component for the reference chart, with the convention behind each."',
             "---", "", "# Ṣaḍbala reconciliation sheet", "",
             f"Generated by `scripts/shadbala_sheet.py` (rule `{sb['rule_version']}`) for the reference chart "
             f"`{c['id']}` ({c['printed_input']}). Values in virūpas (60 = 1 rūpa).", "",
             "**Status.** The reference printout gives each graha's *total* only. A per-component delta needs the "
             "reference's own component values, which are not yet on file; the component columns below are ESHANA's "
             "side of the sheet, and no component has been tuned to close a total.", "",
             "## Components and totals", "",
             "| Graha | Sthāna | Dig | Kāla | Ceṣṭā | Naisargika | Dṛk | ESHANA total | Printed total | Δ |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for g in GRAHAS:
        x = v[g]
        lines.append(f"| {g} | {f(x['sthana']['total'])} | {f(x['dig'])} | {f(x['kala']['total'])} | {f(x['chesta'])} "
                     f"({x.get('chesta_state', '')}) | {f(x['naisargika'])} | {f(x['drik'])} | {f(x['total_virupa'])} | "
                     f"{printed[g]} | {x['total_virupa'] - printed[g]:+.1f} |")
    lines += ["", "## Kāla parts", "", "| Graha | Natonnata | Pakṣa | Tribhāga | Abda | Māsa | Vāra | Horā | Ayana |",
              "|---|---|---|---|---|---|---|---|---|"]
    for g in GRAHAS:
        k = v[g]["kala"]
        lines.append("| " + " | ".join([g] + [f(k[p]) for p in ["natonnata", "paksha", "tribhaga", "abda", "masa", "vara", "hora", "ayana"]]) + " |")
    lines += ["", f"Year, month, weekday and hour lords used: {json.dumps(sb['value']['sky'], ensure_ascii=False)}.", "",
              "## The convention behind each component", "", "| Component | ESHANA | Where programs differ |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {d} |" for a, b, d in CONVENTIONS]
    lines += ["", "## What the totals suggest (not yet attributed)", "",
              "- Every graha but the Sun is below the printed total, by 25 to 66 virūpas; the Sun is above by about 41. "
              "A shortfall spread over most grahas points first to ceṣṭā (motion states vs the cheṣṭā-kendra formula) "
              "and to the year and month lords in kāla bala.",
              "- The Sun's excess with a near-zero ceṣṭā and ayana suggests the reference treats the Sun's horā and "
              "māsa lordships, or its dṛk bala, differently.",
              "- These are hypotheses to test against component values, not corrections. To finish the sheet: supply "
              "the reference program's six-component table for this chart (or approve an offline open-source oracle), "
              "then record each delta here with its convention.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
