#!/usr/bin/env python3
"""Generate crates/eshana-ephemeris/src/vsop87.rs from the VSOP87B files (IMCCE, Bretagnon & Francou 1988).

VSOP87B gives heliocentric spherical coordinates (L, B in radians, R in AU) in the dynamical ecliptic and equinox of
J2000, as Poisson series in T = Julian millennia (TDB) from J2000: Σ_k T^k Σ A cos(B + C T). The series are
truncated here: a term is kept when it can contribute more than `EPS` over a millennium (rad for L and B, AU × the
planet's mean distance for R), which keeps the truncation error near 0.02″ between 1000 and 3000.

    curl -O https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87B.{mer,ven,ear,mar,jup,sat,ura,nep}
    python scripts/vsop87_tables.py DIR_WITH_THE_FILES [--check]

The SHA-256 of each source file is written into the generated module so the table can be traced to its input.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "eshana-ephemeris" / "src" / "vsop87.rs"
PLANETS = [("mer", "MERCURY", 0.387), ("ven", "VENUS", 0.723), ("ear", "EARTH", 1.0), ("mar", "MARS", 1.524),
           ("jup", "JUPITER", 5.203), ("sat", "SATURN", 9.537), ("ura", "URANUS", 19.19), ("nep", "NEPTUNE", 30.07)]
EPS = 1e-7


def parse(path: Path):
    series = {}  # (variable 1..3, power) -> [(A, B, C)]
    cur = None
    for line in path.read_text().splitlines():
        if line.startswith(" VSOP87"):
            var = int(line.split("VARIABLE")[1].split()[0])
            power = int(line.split("*T**")[1].split()[0])
            cur = series.setdefault((var, power), [])
        elif line.strip():
            a, b, c = (float(x) for x in line.split()[-3:])
            cur.append((a, b, c))
    return series


def main() -> int:
    src = Path(sys.argv[1])
    parts = ["// Generated by scripts/vsop87_tables.py from the VSOP87B files of IMCCE (Bretagnon & Francou 1988). Do not edit.",
             "// Terms kept when they can reach 1e-7 (rad for L and B; AU x mean distance for R) within a millennium.",
             "#![allow(clippy::unreadable_literal, clippy::excessive_precision, clippy::approx_constant)]",
             "",
             "/// One series: terms (A, B, C) of A cos(B + C T).",
             "pub type Series = &'static [(f64, f64, f64)];",
             "/// L, B and R, each as powers T^0 … T^5.",
             "pub type Planet = [[Series; 6]; 3];",
             ""]
    total = 0
    for code, name, dist in PLANETS:
        f = src / f"VSOP87B.{code}"
        digest = hashlib.sha256(f.read_bytes()).hexdigest()
        s = parse(f)
        parts.append(f"/// {name.title()}: VSOP87B.{code}, sha256 {digest}.")
        rows = []
        for var in (1, 2, 3):
            powers = []
            for k in range(6):
                eps = EPS * (dist if var == 3 else 1.0)
                terms = [t for t in s.get((var, k), []) if abs(t[0]) >= eps]
                total += len(terms)
                powers.append("&[" + ", ".join(f"({a!r}, {b!r}, {c!r})" for a, b, c in terms) + "]")
            rows.append("[" + ", ".join(powers) + "]")
        parts.append(f"pub static {name}: Planet = [" + ", ".join(rows) + "];")
        parts.append("")
    text = "\n".join(parts)
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("vsop87 tables ok" if ok else f"{OUT} differs from the generator output")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {total} terms, {len(text) // 1024} KiB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
