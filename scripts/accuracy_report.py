#!/usr/bin/env python3
"""Write benchmarks/accuracy/birth-chart-accuracy.md: measured worst cases behind accuracy/tolerances.json.

    ESHANA_SPK=/path/de440s.bsp .venv/bin/python scripts/accuracy_report.py [--check]

``--check`` fails if a measured worst case is at or above its tolerance (the tolerances must keep a margin).
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import statistics
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "accuracy"))
import lib  # noqa: E402

OUT = ROOT / "benchmarks" / "accuracy" / "birth-chart-accuracy.md"


def measure():
    ref = lib.load("swiss_charts.json")["charts"]
    tol = lib.tolerances()
    res = {}
    for prov, spk in lib.providers():
        errs = collections.defaultdict(list)
        cats = collections.Counter({"disagreements": 0})
        n = 0
        for row in ref:
            if row["range"] == "spk" and prov != "spk":
                continue
            n += 1
            for node in ("mean", "true"):
                env = lib.eshana_chart(row, prov, spk, node=node)
                ddt = env["input"]["delta_t_s"] - row["delta_t_s"]
                errs["delta_t_diff_s"].append(abs(ddt))
                for b, p in lib.positions(env).items():
                    if b == "south_node" or (node == "true" and b != "true_node"):
                        continue
                    corr = p["speed_deg_per_day"] * ddt / 86400
                    errs[b].append(abs(lib.adiff(p["longitude_deg"] - corr, row["sidereal"][b]["lon"])) * 3600)
                    if b == "moon":
                        errs["moon_uncorrected"].append(abs(lib.adiff(p["longitude_deg"], row["sidereal"][b]["lon"])) * 3600)
            env = lib.eshana_chart(row, prov, spk)
            sun = lib.positions(env)["sun"]
            eff = (sun["tropical_longitude_deg"] - sun["longitude_deg"]) % 360
            errs["ayanamsha"].append(abs(eff - row["ayanamsha"]["lahiri"]) * 3600)
            at = lib.attrs(env)
            for b in [x for x in lib.PLANETS] + ["mean_node"]:
                sw = row["sidereal"][b]["lon"]
                t = tol["body_arcsec"][prov][b] / 3600
                if lib.near_boundary(sw, lib.PADA, t):
                    cats["skipped (within tolerance of a pada boundary)"] += 1
                    continue
                nk = at[f"vedic.{b}.nakshatra"]
                cats["rashi, nakshatra and pada compared"] += 1
                if (at[f"vedic.{b}.rashi"]["index"], nk["index"], nk["pada"]) != (lib.sign(sw), lib.nakshatra(sw), lib.pada(sw)):
                    cats["disagreements"] += 1
            for hs, code in (("whole_sign", "W"), ("equal", "E"), ("placidus", "P")):
                if code not in row["houses"]:
                    cats["polar Placidus refused (ESH-LATITUDE)"] += 1
                    continue
                for system, z in (("vedic", "sidereal"), ("western", "tropical")):
                    e = lib.eshana_chart(row, prov, spk, system=system, houses=hs)
                    r = row["houses"][code][z]
                    errs[f"asc ({z})"].append(abs(lib.adiff(e["houses"]["ascendant"]["longitude_deg"], r["asc"])) * 3600)
                    errs[f"mc ({z})"].append(abs(lib.adiff(e["houses"]["midheaven"]["longitude_deg"], r["mc"])) * 3600)
                    errs[f"cusps {hs}"].append(max(abs(lib.adiff(c, r["cusps"][i])) for i, c in enumerate(e["houses"]["cusps_deg"])) * 3600)
        res[prov] = (n, errs, cats)
    return res, tol


def write(res, tol) -> str:
    lines = [
        "# Birth-chart accuracy", "",
        "Generated by `scripts/accuracy_report.py` from the suite in [`accuracy/`](../../accuracy/). Reference: Swiss "
        "Ephemeris (pyswisseph, Moshier ephemeris) as an **offline oracle**, numbers only, plus published values. "
        "Longitudes are compared after correcting for the stated difference between the two delta-T models (future "
        "delta-T is a forecast). The uncorrected Moon is shown too, so nothing is hidden.", "",
    ]
    for prov, (n, errs, cats) in res.items():
        lines += [f"## `{prov}` provider ({n} charts)", "", "| quantity | worst (arcsec) | median (arcsec) | tolerance (arcsec) |",
                  "|---|---:|---:|---:|"]
        for k, v in errs.items():
            if k == "delta_t_diff_s":
                continue
            t = tol["body_arcsec"][prov].get(k)
            if t is None:
                t = (tol["ayanamsha_arcsec"] if k == "ayanamsha" else tol["angles_arcsec"] if k.startswith(("asc", "mc"))
                     else 0.000001 if k == "cusps whole_sign" else tol["cusps_arcsec"] if k.startswith("cusps") else "—")
            lines.append(f"| {k} | {max(v):.2f} | {statistics.median(v):.2f} | {t} |")
        dt = errs["delta_t_diff_s"]
        lines += ["", f"Delta-T difference ESHANA vs Swiss: worst {max(dt):.1f} s, median {statistics.median(dt):.1f} s "
                  "(after 2027 both are forecasts).", "", "| categorical check | count |", "|---|---:|"]
        lines += [f"| {k} | {v} |" for k, v in sorted(cats.items())]
        lines.append("")
    lines += ["## Published values", "",
              "| source | what is compared | result |", "|---|---|---|",
              "| Calendar Reform Committee (1955) | Lahiri = 23°15′00″ on 1956-03-21 0h | within 3″ (test `test_lahiri_definition_1956`) |",
              "| ProKerala, sidereal planet positions, read 2026-11-20 | 10 grahas + lagna: degree, rashi, nakshatra, pada, retrograde, house | all agree within the stated tolerances (test `test_prokerala_snapshot`) |",
              ""] + prokerala_table() + [""] + feature_tables() + ["", "Assumptions for each published source are recorded next to its numbers in "
              "[`accuracy/reference/published.json`](../../accuracy/reference/published.json).", ""]
    return "\n".join(lines)


def feature_tables() -> list:
    """Measured worst cases of the Vedic-feature checks: rise/set and ingresses against Swiss, special lagnas
    against PyJHora."""
    import math
    ref = lib.load("swiss_charts.json")
    out = ["## Pañcāṅga, ingresses and special lagnas", ""]
    for prov, spk in lib.providers():
        worst = {k: 0.0 for k in ("sunrise", "sunset", "moonrise", "moonset")}
        for row in ref["charts"]:
            if row["range"] != "analytic":
                continue
            req = {"op": "panchanga", "chart": {"when": {"date": row["date"], "time": "12:00", "timezone": row["timezone"]},
                   "place": {"latitude": row["lat"], "longitude": row["lon"]},
                   "config": {"provider": prov, "zodiac": "sidereal", "ayanamsha": "lahiri"}}}
            if spk:
                req["chart"]["spk_path"] = spk
            p = lib.run(req)["panchanga"]
            for k in worst:
                r, g = row["rise_set"].get(k), p.get(k)
                if r and g and abs(g["jd_ut"] - r) < 0.5:
                    worst[k] = max(worst[k], abs(g["jd_ut"] - r) * 86400 * math.cos(math.radians(row["lat"])))
        out.append(f"- `{prov}`: worst rise/set difference vs Swiss (upper limb, latitude-normalised): "
                   + ", ".join(f"{k} {v:.1f} s" for k, v in worst.items()))
        for body in ("sun", "jupiter", "saturn"):
            req = {"op": "ingresses", "body": body, "start_utc": "1990-01-01T00:00:00Z", "end_utc": "2030-01-01T00:00:00Z",
                   "config": {"provider": prov, "zodiac": "sidereal", "ayanamsha": "lahiri"}}
            if spk:
                req["spk_path"] = spk
            got = lib.run(req)["ingresses"]
            diffs = []
            for r in ref["ingresses"][body]:
                same = [abs(g["jd_ut"] - r["jd_ut"]) for g in got if g["to_sign"] == r["to_sign"] and g["from_sign"] == r["from_sign"]]
                if same:
                    diffs.append(min(same) * 24)
            out.append(f"  - {body} sidereal ingresses 1990-2030: {len(got)} found vs {len(ref['ingresses'][body])} Swiss; "
                       f"worst {max(diffs):.2f} h, median {statistics.median(diffs):.2f} h")
    out += ["", "Special lagnas against PyJHora (Chennai 1996-12-07 10:34, centre-of-disc sunrise, Sun at birth):", ""]
    pub = lib.load("published.json")
    for ex in pub.get("pyjhora_special_lagnas", []):
        req = {"op": "panchanga", "chart": {"when": {"date": ex["date"], "time": ex["time"], "utc_offset_minutes": ex["utc_offset_minutes"]},
               "place": {"latitude": ex["lat"], "longitude": ex["lon"]}, "config": {"zodiac": "sidereal", "ayanamsha": "lahiri"},
               "sunrise": ex["conventions"]["sunrise"], "special_lagna_sun": ex["conventions"]["special_lagna_sun"]}}
        sl = lib.run(req)["panchanga"]["special_lagnas"]
        signs = {"Ar": 0, "Ta": 1, "Ge": 2, "Cn": 3, "Le": 4, "Vi": 5, "Li": 6, "Sc": 7, "Sg": 8, "Cp": 9, "Aq": 10, "Pi": 11}
        import re
        out += ["| lagna | PyJHora | ESHANA − PyJHora |", "|---|---|---:|"]
        for k, v in ex["printed"].items():
            d, sg, mi, se = re.match(r"(\d+)([A-Za-z]{2})(\d+)'([\d.]+)", v).groups()
            want = signs[sg] * 30 + int(d) + int(mi) / 60 + float(se) / 3600
            out.append(f"| {k} | {v} | {lib.adiff(sl[k]['longitude_deg'], want) * 60:+.2f}′ |")
    out.append("")
    return out


def prokerala_table() -> list:
    pub = lib.load("published.json")
    out = []
    for snap in pub["prokerala_snapshots"]:
        provs = lib.providers()
        out += [f"### {snap['id']}", "", f"Printed input: {snap['printed_input']}. Differences are ESHANA minus "
                "the printed value (printed to 0.001°, so ±1.8″ is rounding).", "",
                "| graha | printed | " + " | ".join(f"{p} diff (arcsec)" for p, _ in provs) + " |",
                "|---|---:|" + "---:|" * len(provs)]
        envs = []
        for prov, spk in provs:
            req = {"op": "chart", "system": "vedic",
                   "when": {"date": snap["date"], "time": snap["time"], "utc_offset_minutes": snap["utc_offset_minutes"]},
                   "place": {"latitude": snap["lat"], "longitude": snap["lon"]},
                   "config": {"provider": prov, "zodiac": "sidereal", "ayanamsha": "lahiri", "node_model": snap["node"]}}
            if spk:
                req["spk_path"] = spk
            envs.append(lib.run(req))
        for b, pr in snap["printed"].items():
            cells = []
            for env in envs:
                lon = env["houses"]["ascendant"]["longitude_deg"] if b == "lagna" else lib.positions(env)[b]["longitude_deg"]
                cells.append(f"{lib.adiff(lon, pr['full_deg']) * 3600:+.1f}")
            out.append(f"| {b} | {pr['full_deg']} {pr['rashi']} · {pr['nakshatra']} {pr['pada']} | " + " | ".join(cells) + " |")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    res, tol = measure()
    text = write(res, tol)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(text)
    if a.check:
        bad = []
        for prov, (_, errs, _) in res.items():
            for b, t in tol["body_arcsec"][prov].items():
                if b in errs and max(errs[b]) >= t:
                    bad.append(f"{prov} {b}: worst {max(errs[b]):.2f} >= tolerance {t}")
        if bad:
            print("\n".join(bad), file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
