#!/usr/bin/env python3
"""Check that the reference docs describe what the installed wheel actually does, and regenerate the method list.

    python scripts/check_capabilities.py            # check (exit 1 with the differences)
    python scripts/check_capabilities.py --write    # rewrite docs/reference/methods.md from the wheel

Compared, in both directions:
- every operation in `info.operations` has a row in docs/reference/request.md, and every row is an operation;
- every error code in `info.error_codes` has a row in docs/reference/errors.md, and every row is a code;
- every CLI subcommand in `eshana --help` is in docs/reference/cli.md and in acceptance/capabilities.yaml;
- docs/reference/methods.md equals the page generated from the wheel's `methods` registry.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "docs" / "reference"


def methods_page(listing: dict) -> str:
    lines = ["---", 'title: "Methods"',
             'description: "Every method family and id the engine implements; generated from the wheel."', "---", "",
             "# Methods", "",
             "Generated by `scripts/check_capabilities.py --write` from the `methods` operation (`eshana methods`). "
             "A request names a method by its id; an id not listed here is refused with `ESH-METHOD`, never replaced "
             "by a default. Status: `stable` (fixed default behaviour), `opt_in` (stable, used only when asked), "
             "`experimental` (incomplete; results say what is missing).", ""]
    for fam in listing["families"]:
        lines += [f"## `{fam['family']}`", "", "| Id | Status | What it is |", "|---|---|---|"]
        lines += [f"| `{m['id']}` | {m['status']} | {m['note']} |" for m in fam["methods"]]
        lines.append("")
    return "\n".join(lines)


def table_ids(path: Path, section: str | None = None) -> set[str]:
    text = path.read_text(encoding="utf-8")
    if section:  # only the table under this heading
        text = text.split(section, 1)[1]
        text = re.split(r"^## ", text, maxsplit=1, flags=re.M)[0]
    text = re.sub(r"^.*\n(?=\|---)", "", text, flags=re.M)  # drop table header rows
    return set(re.findall(r"^\| `([A-Za-z0-9_-]+)`", text, re.M))


def cli_commands(binary: str) -> set[str]:
    out = subprocess.run([binary, "--help"], capture_output=True, text=True, check=True).stdout
    block = out.split("Commands:", 1)[1].split("Options:", 1)[0]
    return {line.split()[0] for line in block.splitlines() if line.strip() and line.startswith("  ")} - {"help"}


def check(write: bool = False) -> list[str]:
    from eshana import ChartEngine

    info = ChartEngine.info()
    problems: list[str] = []
    ops, rows = set(info["operations"]), table_ids(REF / "request.md", "## `op` values")
    problems += [f"request.md lacks the operation `{o}`" for o in sorted(ops - rows)]
    problems += [f"request.md documents `{o}`, which the wheel does not have" for o in sorted(rows - ops)]
    codes, rows = {e["code"] for e in info["error_codes"]}, table_ids(REF / "errors.md")
    problems += [f"errors.md lacks `{c}`" for c in sorted(codes - rows)]
    problems += [f"errors.md documents `{c}`, which the wheel does not have" for c in sorted(rows - codes)]
    binary = os.environ.get("ESHANA_BIN", "eshana")
    cmds = cli_commands(binary)
    cli_md = (REF / "cli.md").read_text(encoding="utf-8")
    surface = (ROOT / "acceptance" / "capabilities.yaml").read_text(encoding="utf-8")
    problems += [f"cli.md lacks `eshana {c}`" for c in sorted(cmds) if f"`eshana {c}" not in cli_md]
    problems += [f"capabilities.yaml surface lacks `eshana {c}`" for c in sorted(cmds) if f"- eshana {c}\n" not in surface]
    page = methods_page(ChartEngine.methods())
    target = REF / "methods.md"
    if write:
        target.write_text(page + "\n", encoding="utf-8")
    elif not target.exists() or target.read_text(encoding="utf-8") != page + "\n":
        problems.append("docs/reference/methods.md is stale: run scripts/check_capabilities.py --write")
    return problems


if __name__ == "__main__":
    found = check(write="--write" in sys.argv)
    for p in found:
        print("✗", p)
    print("capabilities: OK" if not found else f"capabilities: {len(found)} difference(s)")
    sys.exit(1 if found else 0)
