#!/usr/bin/env python3
"""Write planning/PROGRESS.md: where ESHANA stands against its plan, from planning/backlog.json and CHANGELOG.md.

    python3 scripts/progress_report.py          # write
    python3 scripts/progress_report.py --check  # fail if the file is stale

Done means verified or released (evidence required); implemented means code exists but is not yet proven.
"""
from __future__ import annotations

import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKLOG = ROOT / "planning/backlog.json"
OUT = ROOT / "planning/PROGRESS.md"
DONE = {"verified", "released"}
ORIGINAL = "Original plan (master plan and ADRs)"
DELIVERED = "Delivered in 0.1–0.3"


def milestone(t: dict) -> str:
    if t.get("milestone"):
        return t["milestone"]
    src = t.get("source", "")
    if t["status"] in DONE and not src.startswith("master plan"):
        return DELIVERED
    if src.startswith("master plan") or src.startswith("ADR"):
        return ORIGINAL if t["status"] not in DONE else DELIVERED
    return ORIGINAL if t["status"] not in DONE else DELIVERED


def bar(done: int, total: int, width: int = 20) -> str:
    k = round(width * done / total) if total else 0
    return "█" * k + "░" * (width - k)


def mark(t: dict) -> str:
    return "[x]" if t["status"] in DONE else "[~]" if t["status"] == "implemented" else "[ ]"


def releases() -> list[str]:
    log = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    return [f"{v} ({d})" for v, d in re.findall(r"^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})", log, re.M)]


def render() -> str:
    data = json.loads(BACKLOG.read_text(encoding="utf-8"))
    tasks, areas = data["tasks"], {a["id"]: a["title"] for a in data["areas"]}
    groups: "OrderedDict[str, list]" = OrderedDict()
    order = [DELIVERED, "0.4 · review round 1", "0.4 · review round 2", "0.4 · review round 3", "0.4 · review round 4", "0.5 · reference chart library", ORIGINAL]
    for name in order:
        groups[name] = []
    for t in tasks:
        groups.setdefault(milestone(t), []).append(t)
    done = sum(t["status"] in DONE for t in tasks)
    out = ["# ESHANA progress", "",
           "<!-- Generated by scripts/progress_report.py from planning/backlog.json. Do not edit by hand. -->", "",
           f"**{done} of {len(tasks)} tasks done** ({round(100 * done / len(tasks))}%)  `{bar(done, len(tasks))}`", "",
           "Done means *verified* or *released*, with evidence; `[~]` means *implemented* (code exists, not yet proven). "
           "The full ledger with evidence is [TRACKING.md](TRACKING.md); the readable plan is [NEXT-STEPS.md](NEXT-STEPS.md).", "",
           "Released: " + ", ".join(releases()) + " (PyPI `eshana`).", "", "## Milestones", "",
           "| Milestone | Done | Open | Progress |", "|---|---:|---:|---|"]
    for name, ts in groups.items():
        if not ts:
            continue
        d = sum(t["status"] in DONE for t in ts)
        out.append(f"| {name} | {d} | {len(ts) - d} | `{bar(d, len(ts), 12)}` {round(100 * d / len(ts))}% |")
    for name, ts in groups.items():
        if not ts or name in (DELIVERED, ORIGINAL):
            continue
        d = sum(t["status"] in DONE for t in ts)
        out += ["", f"## {name} ({d}/{len(ts)})", ""]
        out += [f"- {mark(t)} `{t['id']}` {t['title']}" for t in ts]
    orig = [t for t in groups[ORIGINAL]]
    out += ["", f"## Remaining from the original plan ({len(orig)} open)", "",
            "Grouped by area. These come from the master plan and the ADRs and are not yet built.", ""]
    by_area: "OrderedDict[str, list]" = OrderedDict()
    for t in orig:
        by_area.setdefault(areas.get(t["area"], t["area"]), []).append(t)
    for a, ts in by_area.items():
        out += [f"**{a}**", ""] + [f"- {mark(t)} `{t['id']}` {t['title']}" for t in ts] + [""]
    nxt = [t for t in groups.get("0.4 · review round 2", []) if t["status"] not in DONE][:6] + \
          [t for t in groups.get("0.5 · reference chart library", []) if t["status"] not in DONE][:6]
    out += ["## Next steps", "", "In order: finish the open review items, then the reference chart library, then the "
            "rest of the original plan.", ""] + [f"{i}. `{t['id']}` {t['title']}" for i, t in enumerate(nxt, 1)]
    delivered = groups[DELIVERED]
    out += ["", f"## Delivered in 0.1–0.3 ({len(delivered)})", "", "<details><summary>Show all</summary>", ""]
    out += [f"- {mark(t)} `{t['id']}` {t['title']}" for t in delivered] + ["", "</details>", ""]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("planning/PROGRESS.md is stale: run `make tracking`")
            return 1
        print("progress ok")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
