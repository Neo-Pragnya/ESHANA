#!/usr/bin/env python3
"""Write the PyPI long description (crates/eshana-python/README.md) from the repository README.

PyPI cannot follow relative links, and GitHub serves raw SVGs as text, so:
  - images under assets/readme/ and examples/gallery/ load from the GitHub Pages site (served with the right types);
  - other relative links point at the file on GitHub (blob for files, tree for folders).

    python scripts/pypi_readme.py          # write
    python scripts/pypi_readme.py --check  # exit 1 if the PyPI README is stale (used by `make docs-check`)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC, DST = ROOT / "README.md", ROOT / "crates" / "eshana-python" / "README.md"
REPO = "https://github.com/Neo-Pragnya/ESHANA"
SITE = "https://neo-pragnya.github.io/ESHANA"
SITE_DIRS = {"assets/readme/": f"{SITE}/readme/", "examples/gallery/": f"{SITE}/gallery/"}
HEADER = "<!-- Generated by scripts/pypi_readme.py from the repository README.md. Do not edit by hand. -->\n\n"


def absolute(path: str) -> str:
    if re.match(r"^(https?:|mailto:|#)", path):
        return path
    for prefix, base in SITE_DIRS.items():
        if path.startswith(prefix):
            return base + path[len(prefix):]
    target = path.split("#", 1)[0]
    kind = "tree" if (ROOT / target).is_dir() else "blob"
    return f"{REPO}/{kind}/main/{path}"


ALERTS = {"NOTE": "📝 Note", "TIP": "💡 Tip", "IMPORTANT": "❗ Important", "WARNING": "⚠️ Warning", "CAUTION": "🛑 Caution"}


def pypi_only(text: str) -> str:
    """GitHub-only Markdown becomes something PyPI renders: <picture> → its <img>, Mermaid → a link to the diagram on
    GitHub, alerts → bold blockquotes, math → readable code. Code fences are left alone."""
    text = re.sub(r"<picture>.*?(<img [^>]*/>).*?</picture>", r"\1", text, flags=re.S)
    text = re.sub(r"```mermaid\n.*?```", f"> 📊 *A diagram is here on GitHub: [view the README there]({REPO}#readme).*", text, flags=re.S)
    text = re.sub(r"^> \[!(\w+)\]$", lambda m: f"> **{ALERTS.get(m.group(1), m.group(1).title())}**  ", text, flags=re.M)
    text = text.replace("```math\n", "```text\n")
    parts = re.split(r"(```.*?```)", text, flags=re.S)  # inline $…$ math outside code becomes `…`
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r"(?<![\w`$])\$(?!\()([^$`\n]+?)\$", lambda m: "`" + m.group(1).replace("\\text{", "").replace("}", "").replace("{", "") + "`", parts[i])
    return "".join(parts)


def render(text: str) -> str:
    text = pypi_only(text)
    text = re.sub(r'(src|href)="([^"]+)"', lambda m: f'{m.group(1)}="{absolute(m.group(2))}"', text)
    text = re.sub(r"\]\(([^)\s]+)\)", lambda m: f"]({absolute(m.group(1))})", text)
    return HEADER + text


def main() -> int:
    want = render(SRC.read_text(encoding="utf-8"))
    if "--check" in sys.argv:
        if DST.read_text(encoding="utf-8") != want:
            print(f"{DST.relative_to(ROOT)} is stale: run python scripts/pypi_readme.py")
            return 1
        print("pypi readme ok")
        return 0
    DST.write_text(want, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
